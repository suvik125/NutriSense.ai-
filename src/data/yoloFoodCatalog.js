export function getAllSelectableFoodProfiles() {
  const presetItems = ANALYZER_PRESETS.map((p) => ({
    key: p.id,
    name: p.name,
    mealType: p.mealType,
    portion: p.portion,
    calories: p.calories,
    proteinG: p.proteinG,
    carbsG: p.carbsG,
    fatG: p.fatG,
    fiberG: p.fiberG,
    sodiumMg: p.sodiumMg,
    ironMg: p.ironMg,
    image: p.image,
    allergens: p.allergens,
    ingredients: p.ingredients,
  }));
  return [...Object.values(YOLO_NUTRITION_DB), ...presetItems];
}

export function resolveNutritionFromKey(key, confidence = 92, containerContext = null) {
  const presetMatch = ANALYZER_PRESETS.find((p) => p.id === key);
  const base = presetMatch || YOLO_NUTRITION_DB[key] || YOLO_NUTRITION_DB.kacchi_biryani;

  let portionText = base.portion;
  if (containerContext && !portionText.toLowerCase().includes(containerContext.toLowerCase())) {
    portionText = `${base.portion} · Served in ${containerContext}`;
  }

  return {
    ...base,
    confidence: Math.round(confidence),
    portion: portionText,
  };
}
